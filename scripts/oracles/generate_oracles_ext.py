#!/usr/bin/env python3
"""
generate_oracles_ext.py — R6 ULP-push oracle EXPANSION generator.

Emits tests/oracle_data_ext.h with mpmath ground truth for the 19 families
measured at 0 ULP on dense + coarse + edge grids (see docs/ULP_PUSH.md):

  asin, acos, asinh, acosh, atanh, log10, log2, cbrt, erf, sinh, tanh,
  sinpi, cospi, tan, exp2, bessel_i0, bessel_i1 (+ bessel_j0/j1 benign-only)

Rules (fail-safe, documented in PRECISION_CONTRACT.md):
- Skip non-finite truth; skip |truth| < 1e-300 (zero-regime lives in edge
  tests; the ULP harness cannot score exact-zero vs tiny).
- Bessel J vectors additionally require |truth| > 0.3 (benign regime only;
  crossings are an absolute-error regime, see KNOWN_LIMITATIONS).
- Previously-failing points that R6 fixed are INCLUDED deliberately
  (regression value): log10(999.x), erf(1.1), cbrt(100), asinh(8).

Requires: pip install mpmath.  mp.dps = 50 (matches generate_oracles.py).
"""
import sys

try:
    from mpmath import mp, mpf, sin, cos, tan, asin, acos
    from mpmath import log, log10, sinh, tanh, asinh, acosh, atanh
    from mpmath import erf, besselj, besseli, pi
except ImportError:
    print("ERROR: mpmath not installed. Run: pip install mpmath")
    sys.exit(1)

mp.dps = 50


def emit(name, pairs):
    lines = ["static const oracle_entry_t oracle_%s[] = {" % name]
    n = 0
    for x, t in pairs:
        if t != t or t in (mp.inf, mp.ninf):
            continue
        f = float(t)
        if f != f or f in (float('inf'), float('-inf')):
            continue
        if abs(f) < 1e-300 and f != 0.0:
            continue
        if name in ('bessel_j0', 'bessel_j1') and abs(f) <= 0.3:
            continue
        lines.append("    {%.17e, %.17e}," % (float(x), f))
        n += 1
    lines.append("};")
    lines.append("static const int oracle_%s_count = %d;" % (name, n))
    return "\n".join(lines), n


def sinpi_truth(x):
    # Analytic exact values at integers/half-integers (mpmath's pi has a
    # ~1e-51 artifact there; the library returns exact signed zeros/ones).
    if x == int(x):
        return mpf(0)
    if x * 2 == int(x * 2):
        k = int(x * 2)
        return mpf(1) if k % 4 == 1 else (mpf(-1) if k % 4 == 3 else mpf(0))
    return sin(pi * mpf(x))


def cospi_truth(x):
    if x == int(x):
        return mpf(-1) if int(x) % 2 else mpf(1)
    if x * 2 == int(x * 2):
        return mpf(0)
    return cos(pi * mpf(x))


def main():
    out = []
    out.append("/* Auto-generated by scripts/oracles/generate_oracles_ext.py */")
    out.append("/* R6 ULP-push oracle EXPANSION: 19 families at measured 0 ULP. */")
    out.append("#ifndef MATHLIB_ORACLE_DATA_EXT_H")
    out.append("#define MATHLIB_ORACLE_DATA_EXT_H")
    out.append("")
    out.append('#include "oracle_data.h"')
    out.append("")
    total = 0

    fams = {}
    fams['asin'] = [(x, asin(mpf(x))) for x in
                    [-1.0, -0.9, -0.75, -0.5, -0.25, 0.0, 0.25, 0.5, 0.75, 0.9, 1.0]]
    fams['acos'] = [(x, acos(mpf(x))) for x in
                    [-1.0, -0.9, -0.75, -0.5, -0.25, 0.0, 0.25, 0.5, 0.75, 0.9, 1.0]]
    fams['asinh'] = [(x, asinh(mpf(x))) for x in
                     [-10.0, -8.0, -5.0, -2.0, -1.0, -0.5, -0.1, 0.0, 0.1, 0.5, 1.0, 2.0, 5.0, 8.0, 10.0]]
    fams['acosh'] = [(x, acosh(mpf(x))) for x in
                     [1.0, 1.001, 1.1, 1.5, 2.0, 3.0, 5.0, 8.0, 10.0]]
    fams['atanh'] = [(x, atanh(mpf(x))) for x in
                     [-0.99, -0.95, -0.9, -0.5, -0.2, -0.05, 0.0, 0.05, 0.2, 0.5, 0.9, 0.95, 0.99]]
    fams['log10'] = [(x, log10(mpf(x))) for x in
                     [0.1, 0.5, 1.0, 2.0, 2.718281828459045, 10.0, 100.0, 999.5, 1000.0]]
    fams['log2'] = [(x, log(mpf(x), 2)) for x in
                    [0.1, 0.5, 1.0, 2.0, 10.0, 100.0, 999.5, 1000.0]]
    fams['cbrt'] = [(x, (-mp.power(-mpf(x), mpf(1) / 3) if x < 0 else mp.power(mpf(x), mpf(1) / 3))) for x in
                    [-1000.0, -100.0, -27.0, -8.0, -1.0, -0.001, 0.0, 0.001, 1.0, 8.0, 27.0, 100.0, 1000.0]]
    fams['erf'] = [(x, erf(mpf(x))) for x in
                   [-3.0, -2.0, -1.5, -1.1, -1.0, -0.5, 0.0, 0.5, 1.0, 1.1, 1.5, 2.0, 3.0]]
    fams['sinh'] = [(x, sinh(mpf(x))) for x in
                    [-5.0, -2.0, -1.0, -0.5, -0.49, 0.0, 0.49, 0.5, 1.0, 2.0, 5.0]]
    fams['tanh'] = [(x, tanh(mpf(x))) for x in
                    [-5.0, -2.0, -1.0, -0.5, -0.495, -0.005, 0.0, 0.005, 0.495, 0.5, 1.0, 2.0, 5.0]]
    fams['sinpi'] = [(x, sinpi_truth(x)) for x in
                     [-2.0, -1.5, -1.0, -0.5, -0.25, 0.0, 0.25, 0.5, 1.0, 1.5, 2.0, 0.1, -1.996]]
    fams['cospi'] = [(x, cospi_truth(x)) for x in
                     [-2.0, -1.5, -1.0, -0.5, -0.25, 0.0, 0.25, 0.5, 1.0, 1.5, 2.0, -1.88]]
    fams['tan'] = [(x, tan(mpf(x))) for x in
                   [-1.4, -1.0, -0.7984, -0.5, 0.0, 0.5, 0.7984, 1.0, 1.4]]
    fams['exp2'] = [(x, mp.power(2, mpf(x))) for x in
                    [-10.0, -5.0, -1.0, -0.5, 0.0, 0.5, 0.8501, 1.0, 5.0, 10.0]]
    fams['bessel_i0'] = [(x, besseli(0, mpf(x))) for x in
                         [0.01, 0.1, 0.5, 1.0, 2.0, 5.0, 10.0, 18.0]]
    fams['bessel_i1'] = [(x, besseli(1, mpf(x))) for x in
                         [0.01, 0.1, 0.5, 1.0, 2.0, 5.0, 10.0, 18.0]]
    fams['bessel_j0'] = [(x, besselj(0, mpf(x))) for x in
                         [0.1, 0.25, 0.5, 0.75, 1.0, 1.25, 1.5]]
    fams['bessel_j1'] = [(x, besselj(1, mpf(x))) for x in
                         [1.0, 1.25, 1.5, 1.75, 2.0, 2.25, 2.5]]

    for name, pairs in fams.items():
        block, n = emit(name, pairs)
        out.append(block)
        out.append("")
        total += n
        print("  %-10s %d vectors" % (name, n))

    out.append("#endif /* MATHLIB_ORACLE_DATA_EXT_H */")
    out.append("")

    with open("tests/oracle_data_ext.h", "w") as f:
        f.write("\n".join(out) + "\n")
    print("Wrote tests/oracle_data_ext.h: %d vectors total" % total)


if __name__ == "__main__":
    main()
