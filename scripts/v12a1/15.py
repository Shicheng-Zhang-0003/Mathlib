def fail(message: str) -> None:
    print("ERROR: " + message)
    sys.exit(1)


def write_text(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(content)
    print(f"  [write] {path}")


def locate_v12a1() -> tuple[Path, Path]:
    root = Path.cwd()
    candidate = root / "v12A1"
    if candidate.is_dir():
        return root, candidate
    if (root / "scripts" / "oracles").is_dir():
        print("  [note] Running from inside v12A1.")
        return root.parent, root
    fail("Run from the folder that CONTAINS v12A1/, or from inside v12A1/ itself.")


def patch_generator(v12: Path, force: bool) -> None:
    path = v12 / "scripts" / "oracles" / "generate_oracles.py"
    if path.exists() and not force:
        text = path.read_text(encoding="utf-8")
        if MARKER in text:
            print(f"  [skip] {path}: already expanded")
            return
    write_text(path, NEW_GENERATE_ORACLES)


def regenerate_oracle(v12: Path) -> bool:
    """Run the oracle generator to produce oracle_data.h."""
    gen_script = v12 / "scripts" / "oracles" / "generate_oracles.py"
    if not gen_script.exists():
        fail(f"Generator not found: {gen_script}")
    print("  [run] generate_oracles.py ...")
    result = subprocess.run(
        [sys.executable, str(gen_script)],
        cwd=str(v12),
        capture_output=True,
        text=True,
        timeout=120,
    )
    if result.returncode != 0:
        print(f"  [error] Generator failed:")
        print(result.stderr[-1000:] if result.stderr else result.stdout[-1000:])
        return False
    print(f"  [ok] {result.stdout.strip()}")
    return True


def patch_test_oracle(v12: Path, force: bool) -> None:
    path = v12 / "tests" / "test_oracle.c"
    if path.exists() and not force:
        text = path.read_text(encoding="utf-8")
        if MARKER in text:
            print(f"  [skip] {path}: already expanded")
            return
    write_text(path, NEW_TEST_ORACLE)


def archive_self(v12: Path, force: bool) -> None:
    try:
        source = Path(__file__).resolve()
        dest = v12 / "scripts" / "v12a1" / source.name
        if source == dest:
            return
        if dest.exists() and not force:
            print(f"  [skip] {dest}: already archived")
            return
        dest.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(source, dest)
        print(f"  [archive] {dest}")
    except NameError:
        pass


def main() -> int:
    force = "--force" in sys.argv[1:]
    root, v12 = locate_v12a1()

    print("=========================================================")
    print("  MATHLIB v12A1: ORACLE EXPANSION")
    print("=========================================================")
    print(f"  Root:  {root}")
    print(f"  v12A1: {v12}")
    print(f"  Force: {force}")
    print("---------------------------------------------------------")

    print("\n[1/3] generate_oracles.py — expanded generator")
