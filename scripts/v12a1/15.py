    if not regenerate_oracle(v12):
        print("\n  Oracle generation failed. Fix mpmath installation and retry.")
        return 1

    print("\n[3/3] test_oracle.c — expanded validator")
    patch_test_oracle(v12, force)

    archive_self(v12, force)

    print("\n---------------------------------------------------------")
    print("  Oracle expansion complete.")
    print("")
    print("  New oracle coverage:")
    print("    - gamma: 19 entries (positive + negative non-integer)")
    print("    - lgamma: 16 entries")
